# 辅助函数
def determine_alert_level(real_prob: float, ai_prob: float) -> tuple:
    if real_prob >= THRESHOLD:
        return 1, "real"
    else:
        return 0, "AI"

def generate_alert_message(alert: int, ai_prob: float) -> str:
    if alert == 0:
        return "No alert"
    return f"{ai_prob*100:.2f}% generated by AI "
